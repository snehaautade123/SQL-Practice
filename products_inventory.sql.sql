SELECT*FROM PRODUCTS;

SELECT SUM(QUANTITY) AS TOTAL_QUANTITY
FROM PRODUCTS;

SELECT SUM(QUANTITY) AS ELECTRONICS_TOTAL_QUANTITY
FROM PRODUCTS
WHERE CATEGORY='ELECTRONICS' AND PRICE>20000;

SELECT COUNT(*) AS TOTAL_PRODUCTS 
FROM PRODUCTS;

SELECT COUNT(*) AS TOTAL_PRODUCTS 
FROM PRODUCTS
WHERE PRODUCT_NAME LIKE '%PHONE%'

SELECT AVG(PRICE) AS AVERAGE_PRICE
FROM PRODUCTS;

SELECT AVG(PRICE) AS AVERAGE_PRICE
FROM PRODUCTS
WHERE CATEGORY='ACCESSORIES';

SELECT MAX(PRICE) AS MAX_PRICE,
       MIN(PRICE) AS MIN_PRICE
FROM PRODUCTS;

SELECT * FROM PRODUCTS;
SELECT UPPER(CATEGORY) AS UPPERCASE
FROM PRODUCTS;
SELECT LOWER(CATEGORY) AS LOWERCASE
FROM PRODUCTS;
SELECT LENGTH(CATEGORY) AS LENGTH_NUMBERS
FROM PRODUCTS;  
SELECT CONCAT(PRODUCT_NAME,'-',CATEGORY) AS COMBINATION
FROM PRODUCTS;
SELECT SUBSTRING(PRODUCT_NAME,1,5) AS SHORT_NAME
FROM PRODUCTS;

SELECT TRIM('       MONITOR     ') AS TRIM_TEXT;
SELECT REPLACE(PRODUCT_NAME,'PHONE','DEVICE') AS UPDATED
FROM PRODUCTS;

SELECT NOW() AS CURRENT_TIME;
SELECT CURRENT_DATE AS DATE_NUMBER;
SELECT ADDED_DATE, (CURRENT_DATE-ADDED_DATE) AS CURRENT_DATE
FROM PRODUCTS;
SELECT PRODUCT_NAME,
EXTRACT(YEAR FROM ADDED_DATE) AS YEAR,
EXTRACT(MONTH FROM ADDED_DATE) AS MONTH,
EXTRACT(DAY FROM ADDED_DATE) AS DAY
FROM PRODUCTS;

SELECT PRODUCT_NAME,
AGE(CURRENT_DATE,ADDED_DATE) AS AGE_SINCE_ADDED
FROM PRODUCTS; 
SELECT*FROM PRODUCTS;
SELECT PRODUCT_NAME,PRICE,
     CASE
	 WHEN PRICE>=50000 THEN 'EXPENSIVE'
	 WHEN PRICE>=10000 AND PRICE<=49999 THEN 'MODERATE'
	 ELSE 'AFFORDABLE'
	 END AS AFFORADABLE_PRICE
FROM PRODUCTS;

SELECT PRODUCT_NAME ,QUANTITY,
       CASE 
	   WHEN QUANTITY>=10 THEN 'IN STOCK'
	   WHEN QUANTITY>=5 AND QUANTITY<=9 THEN 'LIMITED STOCK'
	   ELSE 'OUT OF STOCK'
	   END AS QUANTITY_STOCK
FROM PRODUCTS;

ALTER TABLE PRODUCTS 
ADD COLUMN DISCOUNT_PRICE NUMERIC(10,2); 
UPDATE PRODUCTS
SET DISCOUNT_PRICE=PRICE*0.9
WHERE PRODUCT_NAME  NOT IN('LAPTOP','DESK');

SELECT PRODUCT_NAME,
COALESCE(DISCOUNT_PRICE,PRICE)
FROM PRODUCTS;
SELECT PRODUCT_NAME,CATEGORY,PRICE,
ROW_NUMBER() OVER(PARTITION BY CATEGORY ORDER BY PRICE DESC) AS ROW_NUM
FROM PRODUCTS;
SELECT PRODUCT_NAME,CATEGORY,PRICE,
SUM(PRICE) OVER(PARTITION BY CATEGORY ORDER BY PRICE ASC) AS ROW_NUM
FROM PRODUCTS;

